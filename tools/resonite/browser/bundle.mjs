// Flatten the export modules into one script the bundled app can carry.
//
//   node browser/bundle.mjs            -> browser/dropcard-resonite.js
//
// index.html is a single self-contained file with no build step and no module loader, so the
// export cannot arrive as an ES module graph. These files import only each other, in a graph
// with no cycles, so concatenating them in dependency order and stripping the import/export
// keywords is enough — no bundler, and the output stays readable and greppable.
//
// The result defines one global, `window.dropcardResonite`, with { exportResonite,
// downloadResonite }. Everything else stays inside the IIFE.
import { readFileSync, writeFileSync } from 'node:fs';

// dependency order, leaves first
const FILES = [
  '../colour.mjs',
  './pack.mjs',
  './raster.mjs',
  './fonts.mjs',
  './overlay.mjs',
  './capture.mjs',
  './encoder.mjs',
  '../scene.mjs',
  './export.mjs',
  './ui.mjs',
];

const strip = (src, name) => {
  let s = src;
  // `import ... from '...'` — every dependency is in this bundle already
  s = s.replace(/^import[\s\S]*?from\s*['"][^'"]+['"];?[ \t]*$/gm, '');
  s = s.replace(/^import\s*['"][^'"]+['"];?[ \t]*$/gm, '');
  // `export const/function/async function/class` -> the declaration alone
  s = s.replace(/^export\s+(?=(const|let|var|function|async|class)\b)/gm, '');
  // `export { a, b };` and `export { a } from '...'` — both are no-ops once flattened
  const reExport = /^export\s*\{[^}]*\}\s*(from\s*['"][^'"]+['"])?;?[ \t]*$/gm;
  const bad = [...s.matchAll(reExport)].filter(m => m[1]);
  if (bad.length) throw new Error(`${name}: re-export from another module is not supported by ` +
                                  `this flattener — ${bad[0][0].trim()}`);
  s = s.replace(reExport, '');
  if (/^\s*export\s/m.test(s)) throw new Error(`${name}: an export survived the strip — ${
    /^\s*export\s.*$/m.exec(s)[0].trim()}`);
  return s.trim();
};

/* Flattening puts every module in one scope, so two files that each declare a `sha256` become
   a syntax error at load — and in a 7MB bundle nobody would find it. Names are checked here
   instead, where the message can say which two files clashed. Only top-level declarations
   matter; anything indented is inside something. */
const topLevelNames = (src) => {
  const out = [];
  for (const m of src.matchAll(/^(?:const|let|var|function|async function|class)\s+([A-Za-z_$][\w$]*)/gm))
    out.push(m[1]);
  return out;
};

const declared = new Map();
const parts = FILES.map(f => {
  const src = strip(readFileSync(new URL(f, import.meta.url), 'utf8'), f);
  for (const n of topLevelNames(src)) {
    if (declared.has(n))
      throw new Error(`'${n}' is declared at the top level of both ${declared.get(n)} and ${f}. ` +
                      `Flattened they share one scope — rename one, or have the second import ` +
                      `the first rather than redeclaring it.`);
    declared.set(n, f);
  }
  return `// ${'─'.repeat(24)} ${f.replace(/^\.\.?\//, '')} ${'─'.repeat(24)}\n${src}`;
});

const out = `/* dropcard — Resonite export.
 *
 * Generated by tools/resonite/browser/bundle.mjs from the modules under tools/resonite/.
 * Do not edit here; edit those and re-run it. The sources are the same ones the Node build
 * and the test harnesses use, so what ships is what was tested.
 */
(function () {
'use strict';

${parts.join('\n\n')}

window.dropcardResonite = { exportResonite, downloadResonite, downloadWithStatus };
})();
`;

const dest = new URL('./dropcard-resonite.js', import.meta.url);
writeFileSync(dest, out);
console.log(`${FILES.length} modules -> ${dest.pathname.split('/').pop()}  ` +
            `${(out.length / 1024).toFixed(1)} KB, ${out.split('\n').length} lines`);
